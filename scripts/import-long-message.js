// 把张曦写给外公的长文以一条留言入库（id 自动生成，created_at 为当前时间毫秒）
const path = require('path');
const Database = require('better-sqlite3');
const db = new Database(path.join(__dirname, '..', 'data', 'db.sqlite'));

const name = '张曦';
const content = `孩提时代，外公在我心里一直是威严、让人敬畏的样子。
我还记得自己很小的时候，不懂事，拿着小锄头在家门口的地坪上挖了一个大坑。几个姨姨在一旁打趣，说外公回来肯定会狠狠批评我。我当时吓得心里发慌，外公回家后，我连抬头看他的勇气都没有。
我也亲眼见过外公严厉的模样。舅舅第一次烫了新潮的头发回家，外公看着格外生气，脸色严肃。那时候的外公，在小小的我眼里，不苟言笑、气场庄重，让人不敢轻易靠近。
学生时代慢慢长大，我眼里的外公，像一座顶天立地的大山。
花甲之年的他，再次经历了白发人送黑发人的锥心之痛。可他从不在人前落泪，所有的委屈、痛苦和难过，全都默默扛在自己心里。他一边细心安慰、照顾外婆，一边依旧日日奔赴工厂，守着家里的事业，日复一日、从不停歇。那时候的外公，是我们全家人的依靠，是撑起整个家的巨人。
等到我成家立业，再回头看外公，才发现他早已温柔又可爱，活成了一个乐观开朗的老顽童。
每次回家看望他，他总是眉眼弯弯，笑容温和。外公生性爱热闹，逢年过节一家人团聚，他最爱陪着晚辈打牌说笑，无论输赢，永远乐呵呵的，从不计较。
平日里，外公也常常给我打电话，问问我的生活琐事、家里的大小事。他总笑着说，就爱听这些家长里短的小八卦，听听晚辈的日常，心里就踏实温暖。
近两年，病痛缠身，硬生生把原本硬朗的外公，折磨得只剩八十来斤。可即便被病痛煎熬，他骨子里的豁达和温柔，从来没有变过。
家里每个人的喜好、日常小事，他都默默记在心里。逢年过节、晚辈生日，大大小小的事情，他依旧记得清清楚楚，安排得妥妥帖帖。
我永远忘不了今年六月，孩子高考出成绩的那天。成绩刚出来不到半个小时，外公的电话就打来了，细细询问孩子的考试情况，满心牵挂。
哪怕到了生命最后的时光，他心里装的依旧是家人。外公离世前一周，姨爷带他去公园晒太阳，身体虚弱的他，还细心叮嘱我：下个月外婆生日不用特意跑回来，过年一起团聚就好。
谁也没有想到，这位一生隐忍苦难、一生乐观善良、一辈子都在心疼家人、事事为晚辈着想的老人，短短一周之后，就永远离开了我们。
外公这一生，吃过太多苦，扛过太多难，却永远把温柔和乐观留给家人。往后岁岁年年，我们永远思念、永远铭记。`;

const exists = db.prepare('select id from messages where name = ? and content = ?').get(name, content);
if (exists) {
  console.log('已存在，跳过:', exists.id);
} else {
  const r = db.prepare('insert into messages (name, content, created_at) values (?, ?, ?)').run(name, content, Date.now());
  console.log('已写入留言 id =', r.lastInsertRowid);
}
db.close();
