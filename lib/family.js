const ALL_MESSAGES = Object.values(MESSAGES).flat();

function normalizeCategory(c) {
  const s = String(c || '').trim();
  if (!s || s === '未分类') return '';
  return CATEGORY_ALIASES[s] || s;
}

function categoryCode(category) {
  const c = normalizeCategory(category);
  if (CATEGORY_CODES[c]) return CATEGORY_CODES[c];
  const safe = c.replace(/[\\/:*?"<>|\s]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 24);
  return safe || 'other';
}

function randomMessage(category) {
  const pool = MESSAGES[normalizeCategory(category)] || MESSAGES['未分类'];
  return pool[crypto.randomInt(pool.length)];
}

function randomUploader() {
  return FAMILY[crypto.randomInt(FAMILY.length)];
}

module.exports = {
  CATEGORY_CODES, CATEGORY_ALIASES, FAMILY, MESSAGES, ALL_MESSAGES,
  normalizeCategory, categoryCode, randomMessage, randomUploader,
};
